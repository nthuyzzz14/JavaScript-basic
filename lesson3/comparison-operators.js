//Comparison

let x = 10;
let y = 5;


console.log(x == y); // so sánh bằng: false

console.log(x === y); // so sánh bằng nhưng phải cùng kiểu dữ liệu: false

console.log(x != y); // so sánh phủ định: true

console.log(x !== y); //so sánh phủ định nhưng phải cùng kiểu dữ liệu: true

console.log(x > y); // lớn hơn: true

console.log(x < y); // nhỏ hơn: false

console.log(x >= y); // lớn hơn hoặc bằng: true

console.log(x <= y); // nhỏ hơn hoặc bằng: false
